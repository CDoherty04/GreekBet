// The composite the LMSR runs
// ---------------------------------------------------------------------------

/// `exp(ln b + x)` vs `b · e^x` — the exact expression `b_small_softplus`
/// evaluates, over every `b` decade and every `x` that reaches the branch.
///
/// This is the number the LMSR's deep-skew accuracy rests on. The report
/// translates the relative bound into base units.
#[test]
fn the_scaled_softplus_term_matches_the_golden_table() {
    let mut worst = (0.0f64, 0u64, 0i128);
    let mut worst_units = 0.0f64;
    let mut checked = 0;
    let mut underflowed = 0;

    for &(b, x, want) in SCALED_EXP_GOLDEN {
        let ln_b = Fixed::from_base_units(b)
            .expect("b fits")
            .ln()
            .expect("b > 0");
        let arg = ln_b
            .checked_add(Fixed::from_raw(x))
            .expect("ln b + x cannot overflow");
        let got = arg
            .exp()
            .unwrap_or_else(|e| panic!("exp(ln {b} + raw {x}) -> {e:?}"))
            .to_raw();
        checked += 1;

        if want == 0 {
            // Both must agree that the term has vanished below half an ulp.
            assert_eq!(got, 0, "b={b} x={x}: expected underflow to 0, got {got}");
            underflowed += 1;
            continue;
        }
        let r = rel(got, want);
        if r > worst.0 {
            worst = (r, b, x);
        }
        // Absolute error in base units — the quantity that actually reaches
        // `cost` and friends.
        let err_units = ulps(got, want) as f64 / 18_446_744_073_709_551_616.0;
        worst_units = worst_units.max(err_units);
    }

    println!(
        "exp(ln b + x) vs b·e^x: {checked} points ({underflowed} correctly underflowed)\n  \
         max rel {:.4e} at b={} x_raw={}\n  \
         max abs {:.3e} base units  (1 base unit = 1e-6 USDC)",
        worst.0, worst.1, worst.2, worst_units
    );

    assert!(
        worst.0 <= COMPOSITE_REL_BOUND,
        "composite rel error {:.4e} exceeds {COMPOSITE_REL_BOUND:.1e}",
        worst.0
    );
    // The bound that matters: the softplus tail must be far below the base unit
    // the result is rounded to. Six orders of magnitude of margin is the claim.
    assert!(
        worst_units < COMPOSITE_ABS_BOUND_UNITS,
        "the scaled softplus term carries {worst_units:.3e} base units of error, above the \
         asserted {COMPOSITE_ABS_BOUND_UNITS:.0e} — it is now close enough to the 1-base-unit \
         rounding step to change a rounded answer"
    );
    assert!(checked >= 140, "golden table shrank to {checked} points");
}

/// The two ends of the reachable band, spelled out: at `b = B_MIN` the branch
/// argument is negative, at `b = B_MAX` it is `+7.63102…`. Both must evaluate.
#[test]
fn the_reachable_band_is_where_the_analysis_says_it_is() {
    let ln_bmax = Fixed::from_base_units(B_MAX).unwrap().ln().unwrap();
    let arg_max = ln_bmax.checked_add(Fixed::from_int(-20)).unwrap();
    let as_f = arg_max.to_raw() as f64 / 18_446_744_073_709_551_616.0;
    println!("b_small_softplus argument at b=B_MAX, x=-20: {as_f:.8} (ln 1e12 - 20)");
    assert!(
        arg_max.is_positive() && (7.63..7.64).contains(&as_f),
        "the positive-branch ceiling moved to {as_f}"
    );
    assert!(arg_max.exp().is_ok());
    assert!(arg_max.to_raw() <= REACHABLE_MAX_RAW);

    let ln_bmin = Fixed::from_base_units(B_MIN).unwrap().ln().unwrap();
    let arg_min = ln_bmin.checked_add(Fixed::from_int(-20)).unwrap();
    assert!(
        arg_min.is_negative(),
        "at b=B_MIN the branch argument should still be negative"
    );
}
